import crypto from "crypto";
import jwt from "jsonwebtoken";
import passport, { isGoogleAuthConfigured } from "../config/passport.js";
import { startSession } from "../services/session.service.js";

const STATE_PURPOSE = "google_oauth_state";
const STATE_TTL_SECONDS = 10 * 60;
const NONCE_COOKIE = "oauth_nonce";
// Cookie is only ever needed on the two Google routes, and is sent on the top-level
// redirect back from Google, which SameSite=Lax allows.
const NONCE_COOKIE_OPTIONS = {
    httpOnly: true,
    secure: true,
    sameSite: "lax",
    path: "/api/auth/google",
};

const frontendUrl = () => (process.env.FRONTEND_URL || "http://localhost:5173").replace(/\/+$/, "");
const redirectToLogin = (res, code) => res.redirect(`${frontendUrl()}/login?error=${code}`);

// deviceId is generated by the frontend with crypto.randomUUID(); accept anything sane of that shape
const isValidDeviceId = (value) => typeof value === "string" && /^[A-Za-z0-9-]{8,64}$/.test(value);

/**
 * GET /api/auth/google?deviceId=...
 * Starts the flow. The deviceId has to survive the round trip through Google, so it travels
 * inside a signed `state` value together with a random nonce. The same nonce is also set as an
 * httpOnly cookie, so the callback can prove it was started by *this* browser (CSRF / login-CSRF).
 */
export function startGoogleAuth(req, res, next) {
    if (!isGoogleAuthConfigured) {
        return redirectToLogin(res, "google_unavailable");
    }
    const { deviceId } = req.query;
    if (!isValidDeviceId(deviceId)) {
        return redirectToLogin(res, "google_failed");
    }

    const nonce = crypto.randomBytes(16).toString("hex");
    const state = jwt.sign(
        { purpose: STATE_PURPOSE, deviceId, nonce },
        process.env.JWT_SECRET,
        { expiresIn: STATE_TTL_SECONDS }
    );
    res.cookie(NONCE_COOKIE, nonce, { ...NONCE_COOKIE_OPTIONS, maxAge: STATE_TTL_SECONDS * 1000 });

    return passport.authenticate("google", {
        scope: ["profile", "email"],
        session: false,
        state,
        prompt: "select_account",
    })(req, res, next);
}

function readState(req) {
    const { state } = req.query;
    const cookieNonce = req.cookies?.[NONCE_COOKIE];
    if (typeof state !== "string" || typeof cookieNonce !== "string") return null;

    let payload;
    try {
        payload = jwt.verify(state, process.env.JWT_SECRET);
    } catch {
        return null;
    }
    if (payload.purpose !== STATE_PURPOSE || !isValidDeviceId(payload.deviceId)) return null;

    const a = Buffer.from(String(payload.nonce));
    const b = Buffer.from(cookieNonce);
    if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) return null;

    return payload;
}

/**
 * GET /api/auth/google/callback
 * Google redirects here. We validate state, let passport exchange the code and resolve the
 * user, then create the same device-session + JWT cookie as a password login and send the
 * browser back to the frontend.
 */
export function googleCallback(req, res, next) {
    if (!isGoogleAuthConfigured) {
        return redirectToLogin(res, "google_unavailable");
    }

    const state = readState(req);
    res.clearCookie(NONCE_COOKIE, NONCE_COOKIE_OPTIONS); // single use either way
    if (!state) {
        return redirectToLogin(res, "google_failed");
    }
    if (req.query.error) {
        // e.g. access_denied when the user clicks "Cancel" on Google's consent screen
        return redirectToLogin(res, "google_denied");
    }

    passport.authenticate("google", { session: false }, async (err, user) => {
        if (err || !user) {
            if (err) console.error("Google OAuth error", err);
            return redirectToLogin(res, err?.code || "google_failed");
        }
        try {
            await startSession(req, res, user, state.deviceId);
            return res.redirect(`${frontendUrl()}/dashboard`);
        } catch (error) {
            console.error("Error creating session after Google OAuth", error);
            return redirectToLogin(res, "google_failed");
        }
    })(req, res, next);
}